#!/bin/bash
# Regenerate firmware/src/weather_icons.h from the Lucide weather SVGs in
# assets/ (lucide-static v0.460.0, ISC). Each icon is rendered at two sizes —
# 120 px for the weather screen's main reading, 48 px for the forecast tiles —
# and converted to white RGB565A8; ui.cpp recolors them at runtime.
#
# Needs rsvg-convert (librsvg) and node with pngjs resolvable (e.g.
# NODE_PATH=/path/to/node_modules).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/firmware/src/weather_icons.h"
ICONS=(sun moon cloud-sun cloud-moon cloud cloud-fog cloud-drizzle cloud-rain cloud-snow cloud-lightning)

{
    echo "#pragma once"
    echo "// Generated by tools/gen_weather_icons.sh — do not hand-edit."
    echo "// Lucide weather icons (lucide-static v0.460.0, ISC license), white RGB565A8."
    echo "#include <stdint.h>"
    echo
    for name in "${ICONS[@]}"; do
        sym=$(echo "$name" | tr '-' '_')
        SYM=$(echo "$sym" | tr '[:lower:]' '[:upper:]')
        for size in 120 48; do
            png="$ROOT/assets/icon_${name}_${size}.png"
            # Thinner strokes on the big render so it reads as the same weight.
            stroke=2; [ "$size" = 120 ] && stroke=1.5
            sed "s/stroke-width=\"2\"/stroke-width=\"$stroke\"/" "$ROOT/assets/icon_${name}.svg" \
                | rsvg-convert -w "$size" -h "$size" -o "$png"
            node "$ROOT/tools/png_to_lvgl.js" "$png" "icon_wx_${sym}_${size}_data" \
                "ICON_WX_${SYM}_${size}_W" "ICON_WX_${SYM}_${size}_H"
            echo
        done
    done
} > "$OUT"

echo "wrote $OUT"
